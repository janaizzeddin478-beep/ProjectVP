    private void updateSummary() {
    // 1. تحديث قائمة الكراسي والسعر (زي ما عملنا قبل)
    lblSS.setText(String.join(", ", selectedSeats));
    lblTP.setText(totalPrice + " JD");

    // 2. كود جديد لحساب عدد مقاعد الـ Normal والـ VIP
    int normalCount = 0;
    int vipCount = 0;

    for (String seat : selectedSeats) {
        if (seat.startsWith("VIP")) {
            vipCount++; // إذا اسم الكرسي بيبدأ بـ VIP زيد عداد الـ VIP
        } else {
            normalCount++; // غير هيك زيد عداد الـ Normal
        }
    }

    // 3. تحديث الـ Labels اللي عندك (تأكدي من أسمائهم في الـ Design)
    lblN.setText(String.valueOf(normalCount));
    lblVIP.setText(String.valueOf(vipCount));
}
   
    
     
