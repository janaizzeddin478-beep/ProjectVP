    private void btnContActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContActionPerformed
        // TODO add your handling code here:
        // 1. حسبة سعر السناكات (بدون نقاط ...)
    double snacksPrice = (qtyP * pP) + (qtyC * pC) + (qtyN * pN) + (qtyM * pM);
    
    // 2. المجموع النهائي (سعر الكراسي اللي وصل + سعر السناكات)
    double total = seatsPrice + snacksPrice;
    
    // 3. نبعث كل المعلومات للصفحة الأخيرة (تأكدي إن الأسماء صح)
    // "Snacks List" هون رح نحط النص اللي فيه أسماء السناكات
    String allSnacks = lblss.getText(); 
    
   // في صفحة السناكات
    ConfirmationPage CON = new ConfirmationPage(movieName, movieTime, movieSeats, seatsPrice, allSnacks, snacksPrice, total);

    
    CON.setVisible(true); // فتح صفحة التأكيد
    this.setVisible(false);
        
      
    }//GEN-LAST:event_btnContActionPerformed

