  private void updateTotal() {
  
    double total = (qtyP * pP) + (qtyC * pC) + (qtyN * pN) + (qtyM * pM);
    lblSP.setText("Total Price: " + total + " JD");

    String items = ""; 
    
    if (qtyP > 0) { items += qtyP + " * Popcorn, "; }
    if (qtyC > 0) { items += qtyC + " * Chocolate, "; }
    if (qtyN > 0) { items += qtyN + " * Nachos, "; } 
    if (qtyM > 0) { items += qtyM + " * Matrix, "; }


    if (items.endsWith(", ")) {
        items = items.substring(0, items.length() - 2);
    }
    
    
    if (items.isEmpty()) {
        items = "None";
    }


    lblss.setText(items); 
}



